class FDTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.out=ROOT/('run-'+str(time.time_ns()));cls.out.mkdir(parents=True)
    def setUp(self):
        root=self.out/self._testMethodName;root.mkdir();self.h=Harness(root)
    def test_unrelated_fd_disappears_required_ownership_survives(self):
        h=self.h;h.drop='9'
        with h.installed():
            self.assertEqual(h.meta.fds(h.pid),{'3':'socket:[888]','4':h.file})
            endpoint=h.meta.endpoint(rec.w.GUEST/'runtime/qmp.sock',h.pid,unix=True)
            assert isinstance(endpoint,dict)
            self.assertTrue(endpoint['fds'])
            h.authenticate()
        self.assertGreaterEqual(h.collected,3)
    def test_required_monitor_missing_or_empty_refuses(self):
        h=self.h
        with h.installed():
            for links in ({},{'4':h.file}):
                with self.subTest(links=links):
                    h.links=links
                    with self.assertRaisesRegex(rec.e.Refusal,'monitor socket inode mismatch'):h.meta.endpoint(rec.w.GUEST/'runtime/qmp.sock',h.pid,unix=True)
    def test_required_disk_missing_refuses_existing_authenticator(self):
        h=self.h;h.links={'3':'socket:[888]'}
        with h.installed(),self.assertRaisesRegex(rec.e.Refusal,'disk FD not verified'):h.authenticate()
    def test_required_targets_disappear_during_collection_refuses(self):
        h=self.h
        with h.installed():
            h.drop='3'
            with self.assertRaisesRegex(rec.e.Refusal,'monitor socket inode mismatch'):h.meta.endpoint(rec.w.GUEST/'runtime/qmp.sock',h.pid,unix=True)
            h.links={'3':'socket:[888]','4':h.file};h.drop='4'
            with self.assertRaisesRegex(rec.e.Refusal,'disk FD not verified'):h.authenticate()
    def test_permission_and_unexpected_read_errors_fail(self):
        h=self.h
        with h.installed():
            for code in (errno.EACCES,errno.EPERM,errno.EIO,errno.ENOTDIR):
                with self.subTest(errno=code):
                    h.read_error=OSError(code,os.strerror(code))
                    with self.assertRaisesRegex(rec.e.Refusal,'authorized metadata read failed'):h.meta.fds(h.pid)
                    assert isinstance(h.last_error,OSError)
                    self.assertEqual(h.last_error.errno,code)
    def test_vanished_directory_fails(self):
        h=self.h;h.listdir_error=FileNotFoundError(errno.ENOENT,'process directory gone')
        with h.installed(),self.assertRaisesRegex(rec.e.Refusal,'directory gone'):h.meta.fds(h.pid)
    def test_wrong_pid_refused_before_collection(self):
        h=self.h
        with h.installed(),self.assertRaisesRegex(rec.e.Refusal,'wrong PID'):h.meta.fds(h.pid+1)
        self.assertEqual(h.collected,0)
    def test_reused_pid_refused_before_collection(self):
        h=self.h;h.data[f'/proc/{h.pid}/stat']=h.stat(99999)
        with h.installed(),self.assertRaisesRegex(rec.e.Refusal,'start changed'):h.meta.fds(h.pid)
        self.assertEqual(h.collected,0)
    def test_identity_drift_after_collection_refuses_snapshot(self):
        h=self.h;original=copy.deepcopy(h.data)
        changes=(('start',lambda:h.data.update({f'/proc/{h.pid}/stat':h.stat(99999)})),('boot',lambda:h.data.update({'/proc/sys/kernel/random/boot_id':'other-boot'})),('cgroup',lambda:h.data.update({f'/proc/{h.pid}/cgroup':'0::/other'})),('invocation',lambda:h.pin.update(invocation='changed-invocation')),('vanished',lambda:h.data.pop(f'/proc/{h.pid}/stat')))
