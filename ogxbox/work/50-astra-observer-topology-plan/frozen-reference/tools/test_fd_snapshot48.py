class ProcNode:
    def __init__(self,path,data):self.path=str(path);self.data=data
    def __truediv__(self,key):return ProcNode(self.path+'/'+str(key),self.data)
    def __str__(self):return self.path
    def read_text(self):
        if self.path not in self.data:raise FileNotFoundError(errno.ENOENT,'fixture process vanished',self.path)
        return self.data[self.path]
    def read_bytes(self):return b'fixture config'
    def is_socket(self):return True

